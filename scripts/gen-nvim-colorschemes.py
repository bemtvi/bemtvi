#!/usr/bin/env python3
"""Port neovim's bundled colorschemes to bemtvi.

Writes one `crates/bemtvi-server/runtime/colors/<name>.lua` per scheme in
`vendor/neovim/runtime/colors/` (every `*.vim` plus `vim.lua`).

The schemes are Vimscript: generated by Colortemplate, with branches on
`&background`, `&termguicolors` and `&t_Co`, and each starts by sourcing
`colors/vim.lua`, whose `:hi clear` restores neovim's built-in defaults (the
tables in `src/nvim/highlight_group.c`). Rather than re-implement that, this
script runs real neovim on the vendored runtime once per `'background'` with
`'termguicolors'` on, and reads back the final highlight table with
`nvim_get_hl`. What lands in the Lua file is exactly what neovim paints in a
truecolor UI: the scheme, the `vim.lua` base under it, and neovim's defaults
under that.

The translation, applied to every group:

- `fg` / `bg` / `sp` become `#rrggbb`; `link` is kept as a link.
- `bold`, `italic`, `underline`, `undercurl`, `strikethrough` and `reverse`
  carry over. bemtvi has one underline style, so `underdouble` becomes
  `underline`; `standout` becomes `reverse`, as a terminal draws it.
- The `cterm*` values, `blend` and `nocombine` are dropped (bemtvi paints in
  truecolor and has no blending); a group left with nothing is omitted.
- The `Nvim*` groups (neovim's cmdline-expression highlighting) are omitted:
  bemtvi has no such surface.
- `g:terminal_color_*` is not carried over: bemtvi's terminal does not read it.

A scheme that sets `'background'` itself (most of them) gets the same table
for both runs and is written as one table plus `btv.o.background = "<bg>"`. A
scheme that follows `'background'` is written as its shared groups plus an
`if btv.o.background == "light"` split for the rest, so `:set background=light`
reloads it into the light variant.

neovim's own theme, `default.vim`, is written as `neovim.lua`: in bemtvi
`default` is an alias for bemtvi's own scheme.

Usage: scripts/gen-nvim-colorschemes.py   (needs `nvim` on PATH and the
`vendor/neovim` submodule checked out)
"""

import json
import os
import re
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
NVIM_RUNTIME = ROOT / "vendor" / "neovim" / "runtime"
SRC = NVIM_RUNTIME / "colors"
OUT = ROOT / "crates" / "bemtvi-server" / "runtime" / "colors"
# Schemes bemtvi ships under another name (`default` is bemtvi's own scheme).
RENAME = {"default": "neovim"}

DUMP_LUA = r"""
vim.o.termguicolors = true
local out = {}
for _, bg in ipairs({ "dark", "light" }) do
  vim.o.background = bg
  vim.cmd("colorscheme " .. vim.env.BEMTVI_SCHEME)
  out[bg] = { background = vim.o.background, groups = vim.api.nvim_get_hl(0, {}) }
end
io.stdout:write(vim.json.encode(out))
"""

FLAGS = ["bold", "italic", "underline", "undercurl", "strikethrough", "reverse"]
# Attributes bemtvi has no exact equivalent for, and what they become.
DEGRADE = {"underdouble": "underline", "standout": "reverse"}
DROPPED = {"ctermfg", "ctermbg", "cterm", "blend", "nocombine", "default", "force"}


def submodule_rev():
    out = subprocess.run(
        ["git", "-C", str(ROOT / "vendor" / "neovim"), "describe", "--tags", "--always"],
        capture_output=True, text=True, check=True,
    )
    rev = subprocess.run(
        ["git", "-C", str(ROOT / "vendor" / "neovim"), "rev-parse", "--short=10", "HEAD"],
        capture_output=True, text=True, check=True,
    )
    return f"{rev.stdout.strip()} ({out.stdout.strip()})"


def nvim_version():
    # The colour files come from the submodule, but neovim's built-in default
    # groups are compiled into the binary that runs them.
    out = subprocess.run(["nvim", "--version"], capture_output=True, text=True, check=True)
    return out.stdout.splitlines()[0].removeprefix("NVIM ").strip()


def dump(name, script):
    env = dict(os.environ, VIMRUNTIME=str(NVIM_RUNTIME), BEMTVI_SCHEME=name)
    res = subprocess.run(
        ["nvim", "-u", "NONE", "-i", "NONE", "--noplugin", "--headless", "-l", script],
        capture_output=True, text=True, env=env,
    )
    if res.returncode != 0 or res.stderr.strip():
        sys.exit(f"nvim failed on {name}:\n{res.stderr}")
    return json.loads(res.stdout)


def hexcolor(n):
    return f"#{n:06x}"


def translate(group, spec):
    """One nvim_get_hl entry -> the bemtvi opts, as an ordered list of (key, lua) pairs."""
    if "link" in spec:
        return [("link", json.dumps(spec["link"]))]
    unknown = set(spec) - set(FLAGS) - set(DEGRADE) - DROPPED - {"fg", "bg", "sp"}
    if unknown:
        sys.exit(f"{group}: unhandled attribute(s) {sorted(unknown)}")
    opts = []
    for key in ("fg", "bg", "sp"):
        if key in spec:
            opts.append((key, json.dumps(hexcolor(spec[key]))))
    flags = {f for f in FLAGS if spec.get(f)}
    flags |= {DEGRADE[a] for a in DEGRADE if spec.get(a)}
    opts += [(f, "true") for f in FLAGS if f in flags]
    return opts


def table(groups):
    # neovim's group names are case-insensitive and bemtvi's are not, so a link
    # written `PMenu` or `TypeDef` is pointed at the group's own spelling.
    canonical = {name.lower(): name for name in groups}
    out = {}
    for name, spec in groups.items():
        if name.startswith("Nvim"):
            continue
        if "link" in spec:
            spec = {"link": canonical.get(spec["link"].lower(), spec["link"])}
        opts = translate(name, spec)
        if opts:
            out[name] = opts
    return out


def sort_key(name):
    # Normal first (everything else is drawn over it), then plain groups, then
    # the `@capture` groups, each alphabetically.
    return (name != "Normal", name.startswith("@"), name.lower(), name)


def render(groups, indent=""):
    lines = []
    for n in sorted(groups, key=sort_key):
        body = ", ".join(f"{k} = {v}" for k, v in groups[n])
        lines.append(f"{indent}hl(0, {json.dumps(n)}, {{ {body} }})")
    return lines


def header(path):
    """The scheme's own comment header, verbatim: its name, author, licence lines."""
    lead = '"' if path.suffix == ".vim" else "--"
    lines = []
    for line in path.read_text(encoding="utf-8").splitlines():
        if not line.strip():
            if lines:
                break
            continue
        if not line.startswith(lead):
            break
        text = line[len(lead):].rstrip()
        if "Generated by Colortemplate" in text or text.strip() in ("hi clear",):
            continue
        lines.append("--" + (" " + text.lstrip() if text.strip() else ""))
    return [re.sub(r"\t+", " ", l) for l in lines]


def main():
    if not SRC.is_dir():
        sys.exit("vendor/neovim is not checked out: git submodule update --init vendor/neovim")
    rev = submodule_rev()
    binary = nvim_version()
    sources = sorted(p for p in SRC.iterdir() if p.suffix in (".vim", ".lua"))
    with tempfile.TemporaryDirectory() as tmp:
        script = Path(tmp) / "dump.lua"
        script.write_text(DUMP_LUA)
        for path in sources:
            name = RENAME.get(path.stem, path.stem)
            d = dump(path.stem, str(script))
            dark, light = table(d["dark"]["groups"]), table(d["light"]["groups"])
            forced = d["dark"]["background"] == d["light"]["background"] and dark == light
            out = [
                f"-- {name} — ported from neovim's bundled colorscheme: `:colorscheme {name}`.",
                "--",
                "-- The original's header:",
                "--",
                *["--   " + l[3:] if l != "--" else "--" for l in header(path)],
                "--",
                f"-- Generated from `runtime/colors/{path.name}` in neovim {rev} by",
                f"-- `scripts/gen-nvim-colorschemes.py`, which loads the scheme in neovim {binary}",
                "-- with `'termguicolors'` on and writes back the highlight table it ends up with.",
                "-- Do not edit by hand; regenerate. Credits and licences are in",
                "-- `README.md` and `LICENSE.txt` beside this file.",
                "",
                "local hl = btv.hl.define",
                "",
            ]
            if forced:
                out.append(f'btv.o.background = "{d["dark"]["background"]}"')
                out.append(f'btv.g.colors_name = "{name}"')
                out.append("")
                out += render(dark)
            else:
                common = {n: o for n, o in dark.items() if light.get(n) == o}
                only = lambda t: {n: o for n, o in t.items() if n not in common}
                out.append(f'btv.g.colors_name = "{name}"')
                out.append("")
                out += render(common)
                out.append("")
                out.append('if btv.o.background == "light" then')
                out += render(only(light), "  ")
                out.append("else")
                out += render(only(dark), "  ")
                out.append("end")
            (OUT / f"{name}.lua").write_text("\n".join(out) + "\n", encoding="utf-8")
            print(f"{name}: {len(dark)} groups{'' if forced else ' (follows background)'}")


if __name__ == "__main__":
    main()
